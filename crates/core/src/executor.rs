        let stage = fixture
            .destination
            .join("organized")
            .join(&fixture.plan.files[0].stage);
        let deadline = std::time::Instant::now() + std::time::Duration::from_secs(5);
        while !stage.exists() && std::time::Instant::now() < deadline {
            std::thread::sleep(std::time::Duration::from_millis(5));
        }
        let staged = stage.exists();
        let blocked = fixture
            .recover(&AtomicBool::new(false))
            .err()
            .map(|error| error.code);
        cancel.store(true, Ordering::Release);
        assert_eq!(
            worker.join().unwrap().unwrap(),
            CopyOutcome::CanceledWithPartialCopies
        );
        assert!(staged);
        assert_eq!(blocked, Some(ErrorCode::Busy));
        assert_eq!(std::fs::metadata(&stage).unwrap().len(), 0);
        fixture.io.set_paused(false).unwrap();
