#[derive(Clone, Serialize, Deserialize, PartialEq, Eq)]
struct Object {
    volume: u64,
    file: u64,
}
impl Object {
    fn of(file: &File) -> Result<Self> {
        let id = filesystem::identity(file)?;
        Ok(Self {
            volume: id.volume,
            file: id.file,
        })
    }
    fn matches(&self, file: &File) -> Result<bool> {
        Ok(*self == Self::of(file)?)
    }
}
#[derive(Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct CopyFile {
    source: String,
    target: String,
    stage: String,
    object: Object,
    revision: String,
    bytes: u64,
}
#[derive(Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct CopyPlan {
    id: String,
    digest: String,
    source: Object,
    destination: Object,
    source_volume: String,
    destination_volume: String,
    files: Vec<CopyFile>,
}
impl CopyPlan {
    fn digest(&self) -> Result<String> {
        let mut plan = self.clone();
        plan.digest.clear();
        Ok(blake3::hash(
            &serde_json::to_vec(&plan)
                .map_err(|e| failed("Could not encode fixture plan.").caused_by(e))?,
        )
        .to_hex()
        .to_string())
    }
}
fn failed(message: &str) -> AppError {
    AppError::new(ErrorCode::Conflict, message)
}

struct Journal(Connection);
impl Journal {
    fn create(path: &Path, plan: &CopyPlan) -> Result<Self> {
        let journal = Self(Connection::open(path)?);
        journal.0.execute_batch("PRAGMA journal_mode=WAL; PRAGMA synchronous=FULL; CREATE TABLE plan(id TEXT PRIMARY KEY,payload TEXT NOT NULL); CREATE TABLE events(sequence INTEGER PRIMARY KEY,item INTEGER,phase TEXT NOT NULL,evidence TEXT NOT NULL CHECK(json_valid(evidence))); CREATE TRIGGER plan_no_update BEFORE UPDATE ON plan BEGIN SELECT RAISE(ABORT,'Immutable plan'); END; CREATE TRIGGER plan_no_delete BEFORE DELETE ON plan BEGIN SELECT RAISE(ABORT,'Retain plan'); END; CREATE TRIGGER events_no_update BEFORE UPDATE ON events BEGIN SELECT RAISE(ABORT,'Immutable journal'); END; CREATE TRIGGER events_no_delete BEFORE DELETE ON events BEGIN SELECT RAISE(ABORT,'Retain journal'); END;")?;
        journal.0.execute(
            "INSERT INTO plan VALUES(?1,?2)",
            params![
                plan.id,
                serde_json::to_string(plan)
                    .map_err(|e| failed("Could not encode fixture plan.").caused_by(e))?
            ],
        )?;
        Ok(journal)
    }
    fn open(path: &Path, expected: &CopyPlan) -> Result<Self> {
        let journal = Self(Connection::open_with_flags(
            path,
            rusqlite::OpenFlags::SQLITE_OPEN_READ_WRITE,
        )?);
        journal.0.execute_batch("PRAGMA synchronous=FULL;")?;
        let text: String = journal.0.query_row(
            "SELECT payload FROM plan WHERE id=? AND length(payload)<=65536",
            [&expected.id],
            |row| row.get(0),
        )?;
        if text.len() > 65536 {
            return Err(failed("The fixture plan exceeds its bound."));
        }
        let plan: CopyPlan = serde_json::from_str(&text)
            .map_err(|e| failed("The fixture plan is invalid.").caused_by(e))?;
        if plan.digest()? != expected.digest || plan.digest != expected.digest {
            return Err(failed("The immutable fixture plan changed."));
        }
        Ok(journal)
    }
    fn append(&self, item: Option<usize>, phase: &str, evidence: serde_json::Value) -> Result<()> {
        let encoded = evidence.to_string();
        if encoded.len() > crate::operations::MAX_PLAN_BYTES {
            return Err(AppError::new(
                ErrorCode::InvalidInput,
                "Operation evidence exceeds 8 MiB. Retain the current scope and use a smaller selection.",
            ));
        }
        self.0.execute(
            "INSERT INTO events(item,phase,evidence) VALUES(?1,?2,?3)",
            params![item.map(|index| index as i64), phase, encoded],
        )?;
        Ok(())
    }
    fn stage_identity(&self, item: usize) -> Result<Option<filesystem::FileIdentity>> {
        use rusqlite::OptionalExtension;
        let text:Option<String>=self.0.query_row("SELECT evidence FROM events WHERE item=? AND phase='stage_created' ORDER BY sequence DESC LIMIT 1",[item as i64],|row|row.get(0)).optional()?;
        text.map(|text| {
            let object: Object = serde_json::from_str(&text)
                .map_err(|e| failed("Invalid staged identity evidence.").caused_by(e))?;
            Ok(filesystem::FileIdentity {
                volume: object.volume,
                file: object.file,
                links: 1,
            })
        })
        .transpose()
    }
}

fn output_chain(path: &Path) -> Result<DirectoryChain> {
    #[cfg(windows)]
    {
        DirectoryChain::open_for_owned_publication(path)
    }
    #[cfg(not(windows))]
    {
        DirectoryChain::open(path)
    }
}
fn revision(file: &File, plan: &CopyFile) -> Result<()> {
    if !plan.object.matches(file)?
        || source_native::revision(file)? != plan.revision
        || file.metadata()?.len() != plan.bytes
    {
        return Err(failed("The reviewed copy source changed."));
    }
    Ok(())
}
fn source_member(root: &File, plan: &CopyFile) -> Result<()> {
    revision(&native::read(root, &plan.source)?, plan)
}
struct VerifiedBytes {
    digest: String,
    copy_revision: String,
    identity: filesystem::FileIdentity,
}
impl VerifiedBytes {
    fn revalidate(&self, parent: &File, leaf: &str, file: &File) -> Result<()> {
        if filesystem::identity(file)? != self.identity
            || source_native::revision(file)? != self.copy_revision
            || !native::entry_matches(parent, leaf, &self.identity)?
            || filesystem::identity(file)? != self.identity
            || source_native::revision(file)? != self.copy_revision
        {
            return Err(failed(
                "Verified output changed identity, revision or directory membership.",
            ));
        }
        Ok(())
    }
}
fn read_block(
    io: &PacedIo,
    file: &mut File,
    buffer: &mut [u8],
    cancel: &AtomicBool,
) -> Result<IoStep<usize>> {
    let mut used = 0;
    while used < buffer.len() {
        match io.read(file, &mut buffer[used..], cancel)? {
            IoStep::Canceled => return Ok(IoStep::Canceled),
            IoStep::Completed(0) => break,
            IoStep::Completed(count) => used += count,
        }
    }
    Ok(IoStep::Completed(used))
}
fn compare(
    io: &PacedIo,
    source: &mut File,
    copy: &mut File,
    plan: &CopyFile,
    cancel: &AtomicBool,
) -> Result<IoStep<VerifiedBytes>> {
    revision(source, plan)?;
    let identity = filesystem::identity(copy)?;
    let copy_revision = source_native::revision(copy)?;
    if copy.metadata()?.len() != plan.bytes {
        return Err(failed(
            "The copied file length differs from the reviewed source.",
        ));
    }
    source.seek(SeekFrom::Start(0))?;
    copy.seek(SeekFrom::Start(0))?;
    let mut left = [0u8; CHUNK_BYTES];
    let mut right = [0u8; CHUNK_BYTES];
    let mut hash = blake3::Hasher::new();
    let mut total = 0u64;
    loop {
        let requested = plan
            .bytes
            .saturating_sub(total)
            .min(CHUNK_BYTES as u64)
            .max(1) as usize;
        let IoStep::Completed(a) = read_block(io, source, &mut left[..requested], cancel)? else {
            return Ok(IoStep::Canceled);
        };
        let IoStep::Completed(b) = read_block(io, copy, &mut right[..requested], cancel)? else {
            return Ok(IoStep::Canceled);
        };
        if a != b || left[..a] != right[..b] {
            return Err(failed(
                "Full byte verification failed. Retain the source and staged output.",
            ));
        }
        if a == 0 {
            break;
        }
        hash.update(&left[..a]);
        total = total
            .checked_add(a as u64)
            .ok_or_else(|| failed("Copy byte count overflow."))?;
        if total > plan.bytes {
            return Err(failed("A file grew during verification."));
        }
    }
    revision(source, plan)?;
    if total != plan.bytes
        || filesystem::identity(copy)? != identity
        || source_native::revision(copy)? != copy_revision
    {
        return Err(failed("The reviewed source length changed."));
    }
    Ok(IoStep::Completed(VerifiedBytes {
        digest: hash.finalize().to_hex().to_string(),
        copy_revision,
        identity,
    }))
}
fn stop(fault: Option<CopyFault>, phase: CopyFault) -> bool {
    let hit = fault == Some(phase);
    #[cfg(test)]
    if hit && CRASH_ON_FAULT.load(Ordering::Acquire) {
        std::process::exit(77);
    }
    hit
}
#[cfg(test)]
static CRASH_ON_FAULT: AtomicBool = AtomicBool::new(false);

struct CopyContext<'a> {
    plan: &'a CopyPlan,
    journal: &'a Journal,
    source_root: &'a File,
    destination: &'a File,
    io: &'a PacedIo,
    cancel: &'a AtomicBool,
    validate_scope: &'a dyn Fn() -> Result<()>,
}
impl CopyContext<'_> {
    fn execute(&self, fault: Option<CopyFault>) -> Result<CopyOutcome> {
        let Self {
            plan,
            journal,
            source_root,
            destination,
            io,
            cancel,
            validate_scope,
        } = self;
        if !plan.source.matches(source_root)?
            || !plan.destination.matches(destination)?
            || source_native::volume_token(source_root)? != plan.source_volume
            || source_native::volume_token(destination)? != plan.destination_volume
            || plan.digest()? != plan.digest
        {
            return Err(failed("The immutable copy scope changed."));
        }
        let count: i64 = journal
            .0
            .query_row("SELECT count(*) FROM events", [], |row| row.get(0))?;
        if count != 0 {
            return Err(failed(
                "This copy has journal history. Inspect recovery before any retry.",
            ));
        }
        let mut completed = Vec::new();
        for (index, item) in plan.files.iter().enumerate() {
            validate_scope()?;
            if cancel.load(Ordering::Acquire) {
                return Ok(CopyOutcome::CanceledWithPartialCopies);
            }
            let mut source = native::read(source_root, &item.source)?;
            revision(&source, item)?;
            journal.append(Some(index),"item_intent",serde_json::json!({"stage":item.stage,"target":item.target,"sourceRevision":item.revision}))?;
            if stop(fault, CopyFault::AfterIntent) {
                return Ok(CopyOutcome::Interrupted);
            }
            let mut stage = native::create_file(destination, &item.stage)?;
            let identity = filesystem::identity(&stage)?;
            if identity.links != 1 || identity.volume != plan.destination.volume {
                return Err(failed("The owned stage identity is unsupported."));
            }
            journal.append(
                Some(index),
                "stage_created",
                serde_json::to_value(Object::of(&stage)?)
                    .map_err(|e| failed("Could not retain staged identity.").caused_by(e))?,
            )?;
            if stop(fault, CopyFault::AfterStageCreation) {
                return Ok(CopyOutcome::Interrupted);
            }
            let mut buffer = [0u8; CHUNK_BYTES];
            let mut total = 0u64;
            loop {
                let requested = item
                    .bytes
                    .saturating_sub(total)
                    .min(CHUNK_BYTES as u64)
                    .max(1) as usize;
                let IoStep::Completed(count) =
                    io.read(&mut source, &mut buffer[..requested], cancel)?
                else {
                    return Ok(CopyOutcome::CanceledWithPartialCopies);
                };
                if count == 0 {
                    break;
                }
                total = total
                    .checked_add(count as u64)
                    .ok_or_else(|| failed("Copy length overflow."))?;
                if total > item.bytes {
                    return Err(failed("The source grew during copying."));
                }
                if io.write_all(&mut stage, &buffer[..count], cancel)? == IoStep::Canceled {
                    return Ok(CopyOutcome::CanceledWithPartialCopies);
                }
                if fault == Some(CopyFault::InjectedDiskFullAfterChunk) {
                    return Err(std::io::Error::from(std::io::ErrorKind::StorageFull).into());
                }
                if stop(fault, CopyFault::AfterCopyChunk) {
                    stage.sync_all()?;
                    return Ok(CopyOutcome::Interrupted);
                }
            }
            revision(&source, item)?;
            stage.sync_all()?;
            drop(stage);
            journal.append(
                Some(index),
                "stage_flushed",
                serde_json::json!({"bytes":total.to_string()}),
            )?;
            if stop(fault, CopyFault::AfterFlush) {
                return Ok(CopyOutcome::Interrupted);
            }
            let mut verified = native::reopen_stage(destination, &item.stage, &identity)?;
            let IoStep::Completed(witness) = compare(io, &mut source, &mut verified, item, cancel)?
            else {
                return Ok(CopyOutcome::CanceledWithPartialCopies);
            };
            let digest = witness.digest.clone();
            journal.append(
                Some(index),
                "stage_verified",
                serde_json::json!({"bytes":total.to_string(),"digest":digest,"copyRevision":witness.copy_revision}),
            )?;
            if stop(fault, CopyFault::AfterVerification) {
                return Ok(CopyOutcome::Interrupted);
            }
            validate_scope()?;
            revision(&source, item)?;
            source_member(source_root, item)?;
            witness.revalidate(destination, &item.stage, &verified)?;
            if cancel.load(Ordering::Acquire) {
                return Ok(CopyOutcome::CanceledWithPartialCopies);
            }
            journal.append(
                Some(index),
                "publish_intent",
                serde_json::json!({"target":item.target,"stage":item.stage,"digest":digest}),
            )?;
            if stop(fault, CopyFault::BeforePublish) {
                return Ok(CopyOutcome::Interrupted);
            }
            let mut published =
                native::publish_new(destination, &item.stage, verified, &item.target, &identity)?;
            if stop(fault, CopyFault::AfterPublish) {
                return Ok(CopyOutcome::Interrupted);
            }
            if fault == Some(CopyFault::ReadOnlyJournalAfterPublish) {
                journal.0.pragma_update(None, "query_only", true)?;
            }
            let IoStep::Completed(final_witness) =
                compare(io, &mut source, &mut published, item, cancel)?
            else {
                return Ok(CopyOutcome::CanceledWithPartialCopies);
            };
            if final_witness.digest != digest {
                return Err(failed(
                    "Published content changed after staged verification.",
                ));
            }
            validate_scope()?;
            source_member(source_root, item)?;
            final_witness.revalidate(destination, &item.target, &published)?;
            journal.append(
                Some(index),
                "item_completed_verified",
                serde_json::json!({"digest":digest,"copyRevision":final_witness.copy_revision,"object":Object::of(&published)?}),
            )?;
            completed.push(final_witness);
            if stop(fault, CopyFault::AfterItemCommit) {
                return Ok(CopyOutcome::Interrupted);
            }
        }
        validate_scope()?;
        for (item, witness) in plan.files.iter().zip(&completed) {
            source_member(source_root, item)?;
            witness.revalidate(
                destination,
                &item.target,
                &native::read(destination, &item.target)?,
            )?;
        }
        journal.append(
            None,
            "plan_completed_verified",
            serde_json::json!({"files":plan.files.len()}),
        )?;
        if stop(fault, CopyFault::AfterPlanCommit) {
            return Ok(CopyOutcome::Interrupted);
        }
        Ok(CopyOutcome::CompletedVerified)
    }
}

fn inspect_item(
    plan: &CopyFile,
    index: usize,
    journal: &Journal,
    source_root: &File,
    destination: &File,
    io: &PacedIo,
    cancel: &AtomicBool,
) -> Result<RecoveredItem> {
    let mut source = native::read(source_root, &plan.source)?;
    revision(&source, plan)?;
    let published = native::maybe_read(destination, &plan.target)?;
    let stage = native::maybe_read(destination, &plan.stage)?;
    let expected = journal.stage_identity(index)?;
    match (published, stage, expected) {
        (None, None, None) => Ok(RecoveredItem::NotStarted),
        (Some(mut file), None, Some(expected)) if filesystem::identity(&file)? == expected => {
            match compare(io, &mut source, &mut file, plan, cancel)? {
                IoStep::Completed(witness) => {
                    source_member(source_root, plan)?;
                    witness.revalidate(destination, &plan.target, &file)?;
                    Ok(RecoveredItem::PublishedVerified)
                }
                IoStep::Canceled => Err(failed("Recovery inspection was canceled.")),
            }
        }
        (None, Some(mut file), Some(expected)) if filesystem::identity(&file)? == expected => {
            if file.metadata()?.len() != plan.bytes {
                if !native::entry_matches(destination, &plan.stage, &expected)?
                    || filesystem::identity(&file)? != expected
                {
                    return Err(failed(
                        "The retained partial stage changed directory membership.",
                    ));
                }
                source_member(source_root, plan)?;
                return Ok(RecoveredItem::RetainedPartialStage);
            }
            match compare(io, &mut source, &mut file, plan, cancel)? {
                IoStep::Completed(witness) => {
                    source_member(source_root, plan)?;
                    witness.revalidate(destination, &plan.stage, &file)?;
                    Ok(RecoveredItem::StagedVerified)
                }
                IoStep::Canceled => Err(failed("Recovery inspection was canceled.")),
            }
        }
        _ => Err(failed(
            "The staged or published objects do not match the retained operation identity. Retain all files for review.",
        )),
    }
}

/// Sole constructor owns a new random temporary run. There is no path argument,
/// imported approval or way to point this fixture at a real photo library.
pub struct CopyFixture {
    run: tempfile::TempDir,
    source: PathBuf,
    destination: PathBuf,
    plan: CopyPlan,
    io: PacedIo,
    gate: std::sync::Mutex<()>,
}
impl CopyFixture {
    pub fn new() -> Result<Self> {
        let run = tempfile::Builder::new()
            .prefix("stillharbour-m2-copy-")
            .tempdir()?;
        let root = run.path().canonicalize()?;
        let source = root.join("source");
        let destination = root.join("destination");
        std::fs::create_dir(&source)?;
        std::fs::create_dir(&destination)?;
        for (name, bytes) in Self::originals() {
            std::fs::write(source.join(name), bytes)?;
        }
        std::fs::write(
            destination.join("destination-only.bin"),
            b"unique destination bytes",
        )?;
        let source_chain = DirectoryChain::open(&source)?;
        let destination_chain = output_chain(&destination)?;
        let output = native::create_directory(destination_chain.leaf(), "organized")?;
        let token = uuid::Uuid::new_v4().to_string();
        std::fs::write(root.join("fixture-owner"), token.as_bytes())?;
        let mut files = Vec::new();
        for (index, (name, _)) in Self::originals().into_iter().enumerate() {
            let file = native::read(source_chain.leaf(), name)?;
            files.push(CopyFile {
                source: name.into(),
                target: name.into(),
                stage: format!(".stillharbour-{token}-{index}.partial"),
                object: Object::of(&file)?,
                revision: source_native::revision(&file)?,
                bytes: file.metadata()?.len(),
            });
        }
        let mut plan = CopyPlan {
            id: token,
            digest: String::new(),
            source: Object::of(source_chain.leaf())?,
            destination: Object::of(&output)?,
            source_volume: source_native::volume_token(source_chain.leaf())?,
            destination_volume: source_native::volume_token(&output)?,
            files,
        };
        plan.digest = plan.digest()?;
        drop(output);
        drop(destination_chain);
        drop(source_chain);
        Journal::create(&root.join("operation.sqlite"), &plan)?;
        Ok(Self {
            run,
            source,
            destination,
            plan,
            io: PacedIo::shared(),
            gate: std::sync::Mutex::new(()),
        })
    }
    fn originals() -> Vec<(&'static str, Vec<u8>)> {
        vec![
            ("Photo.JPG", vec![0x6d; 180_000]),
            ("Photo.xmp", b"<xmp>owned companion</xmp>".to_vec()),
            ("unknown.bin", Vec::new()),
        ]
    }
    fn scope(&self) -> Result<(DirectoryChain, DirectoryChain)> {
        let base = self.run.path().canonicalize()?;
        if !self.source.starts_with(&base) || !self.destination.starts_with(&base) {
            return Err(failed("The disposable fixture boundary changed."));
        }
        let source = DirectoryChain::open(&self.source)?;
        let output = output_chain(&self.destination.join("organized"))?;
        if !self.plan.source.matches(source.leaf())?
            || !self.plan.destination.matches(output.leaf())?
            || source_native::volume_token(source.leaf())? != self.plan.source_volume
            || source_native::volume_token(output.leaf())? != self.plan.destination_volume
        {
            return Err(failed("The disposable fixture root identity changed."));
        }
        Ok((source, output))
    }
    pub fn run_until(&self, fault: Option<CopyFault>, cancel: &AtomicBool) -> Result<CopyOutcome> {
        let _lock = self.gate.try_lock().map_err(|_| {
            AppError::new(
                ErrorCode::Busy,
                "This owned operation is already running or being inspected.",
            )
        })?;
        let (source, output) = self.scope()?;
        let journal = Journal::open(&self.run.path().join("operation.sqlite"), &self.plan)?;
        let validate_scope = || self.scope().map(|_| ());
        let context = CopyContext {
            plan: &self.plan,
            journal: &journal,
            source_root: source.leaf(),
            destination: output.leaf(),
            io: &self.io,
            cancel,
            validate_scope: &validate_scope,
        };
        let result = context.execute(fault);
        match &result {
            Ok(CopyOutcome::CanceledWithPartialCopies) => {
                journal.append(None, "canceled_with_partial_copies", serde_json::json!({}))?
            }
            Err(error) => {
                let _ = journal.append(
                    None,
                    "needs_attention",
                    serde_json::json!({"code":error.code}),
                );
            }
            _ => {}
        }
        result
    }
    /// Fresh full-byte inspection only: no stage deletion, automatic replay,
    /// journal completion or overwrite is performed on recovery.
    pub fn recover(&self, cancel: &AtomicBool) -> Result<RecoveryReport> {
        let _lock = self.gate.try_lock().map_err(|_| {
            AppError::new(
                ErrorCode::Busy,
                "This owned operation is already running or being inspected.",
            )
        })?;
        let (source, output) = self.scope()?;
        let journal = Journal::open(&self.run.path().join("operation.sqlite"), &self.plan)?;
        let items = self
            .plan
            .files
            .iter()
            .enumerate()
            .map(|(index, item)| {
                match inspect_item(
                    item,
                    index,
                    &journal,
                    source.leaf(),
                    output.leaf(),
                    &self.io,
                    cancel,
                ) {
                    Ok(state) => RecoveredFile {
                        index,
                        state,
                        error: None,
                    },
                    Err(error) => RecoveredFile {
                        index,
                        state: RecoveredItem::NeedsAttention,
                        error: Some(error),
                    },
                }
            })
            .collect::<Vec<_>>();
        self.scope()?;
        let all_outputs_byte_verified = items
            .iter()
            .all(|item| item.state == RecoveredItem::PublishedVerified);
        Ok(RecoveryReport {
            items,
            all_outputs_byte_verified,
        })
    }
    pub fn sources_preserved(&self) -> Result<bool> {
        self.scope()?;
        for (name, bytes) in Self::originals() {
            if std::fs::read(self.source.join(name))? != bytes {
                return Ok(false);
            }
        }
        Ok(
            std::fs::read(self.destination.join("destination-only.bin"))?
                == b"unique destination bytes",
        )
    }
}

