//! Native byte-preservation acceptance. Unsupported media remains opaque data;
//! a successfully backed-up damaged version never replaces an earlier snapshot.
#![cfg(any(windows, target_os = "macos"))]
use super::application_tests::{Fixture, wait};
use super::*;

struct Run {
    fixture: Fixture,
    catalog: String,
    credential: String,
}
impl Drop for Run {
    fn drop(&mut self) {
        self.fixture.library.snapshots.cancel_all();
        let end = Instant::now() + Duration::from_secs(20);
        while !self.fixture.library.snapshots.idle().unwrap_or(false) && Instant::now() < end {
            std::thread::sleep(Duration::from_millis(10));
        }
        if std::thread::panicking() || !self.fixture.library.snapshots.idle().unwrap_or(false) {
            self.fixture._run.disable_cleanup(true);
            return;
        }
        if let Err(error) = CredentialStore::delete_owned(
            &self.catalog,
            CredentialPurpose::Repository,
            &self.credential,
        ) {
            self.fixture._run.disable_cleanup(true);
            panic!("Generated credential cleanup failed: {error:?}");
        }
    }
}

fn start(f: &Fixture, review: &SnapshotReview, action: &str) -> SnapshotJob {
    let s = &f.library.snapshots;
    let approval = s.approve(&review.id, &review.digest, action).unwrap();
    let frozen = s.take_approval(&review.id, &approval.id, action).unwrap();
    let queued = s.start(f.library.clone(), frozen, action).unwrap();
    let done = wait(&f.library, &queued.id);
    assert_eq!(done.state, "completed_verified", "{}", done.message);
    assert!(
        done.included
            && done.structural_checked
            && done.data_read_verified
            && done.restored_compared
    );
    assert!(!done.independent_recovery_verified);
    done
}

#[test]
#[ignore = "Native generated damaged/unknown media preservation with OS vault and pinned helpers"]
fn native_damaged_newer_media_retains_both_versions_and_all_opaque_companions() {
    assert!(std::env::var_os("STILLHARBOUR_M4_GENERATED_REPOSITORY_DRIVE").is_none());
    let f = Fixture::new();
    let helpers = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../vendor/backup-helpers")
        .join(if cfg!(windows) {
            "windows-x86_64"
        } else {
            "macos-aarch64"
        })
        .canonicalize()
        .unwrap();
    f.library.configure_snapshot_helpers(helpers).unwrap();
    let catalog = f.library.catalog.summary().unwrap().id;
    let credential = CredentialStore::store(
        &catalog,
        CredentialPurpose::Repository,
        &uuid::Uuid::new_v4().to_string(),
    )
    .unwrap();
    let run = Run {
        fixture: f,
        catalog,
        credential,
    };
    let f = &run.fixture;
    let mut jpeg = std::io::Cursor::new(Vec::new());
    image::RgbImage::from_pixel(16, 8, image::Rgb([19, 43, 67]))
        .write_to(&mut jpeg, image::ImageFormat::Jpeg)
        .unwrap();
    let good = jpeg.into_inner();
    assert!(image::load_from_memory(&good).is_ok());
    let damaged = good[..16].to_vec();
    assert!(image::load_from_memory(&damaged).is_err());
    // These are deliberately opaque generated bytes, not claimed RAW/video support.
    let mut expected = BTreeMap::from([
        ("original.txt", b"generated preserved original".to_vec()),
        (
            "hidden-source/companion.xmp",
            b"generated sidecar outside gallery filter".to_vec(),
        ),
        ("photo.jpg", good.clone()),
        (
            "photo.vendorraw",
            b"unknown generated RAW-like payload\0\xff".to_vec(),
        ),
        (
            "photo.xmp",
            b"<xmp>unique generated companion</xmp>".to_vec(),
        ),
        ("photo.mp4", b"opaque generated motion component\0".to_vec()),
        (
            ".unrecognized",
            b"hidden generated non-gallery bytes".to_vec(),
        ),
    ]);
    for (relative, bytes) in &expected {
        std::fs::write(f.source.join(relative), bytes).unwrap();
    }
    let neighbor = f.output.join("existing-neighbor.jpg");
    std::fs::write(&neighbor, b"retain this separately generated neighbor").unwrap();
    let selection = Fixture::selection(&f.backup);
    let profile = f
        .library
        .snapshots
        .profile_create(
            &f.library,
            "Generated damaged media preservation".into(),
            vec![f.root.clone()],
            run.credential.clone(),
            None,
            SnapshotDestinationInput::Local {
                selection_id: selection.id.clone(),
            },
            Some(selection),
        )
        .unwrap();
    let mut keys = Vec::new();
    for generation in 0..2 {
        if generation == 1 {
            std::fs::write(f.source.join("photo.jpg"), &damaged).unwrap();
            expected.insert("photo.jpg", damaged.clone());
        }
        let before: BTreeMap<_, _> = expected
            .keys()
            .map(|relative| {
                let file = File::open(f.source.join(relative)).unwrap();
                (
                    *relative,
                    (
                        filesystem::identity(&file).unwrap(),
                        file.metadata().unwrap().modified().unwrap(),
                    ),
                )
            })
            .collect();
        let review = f
            .library
            .snapshots
            .review(f.library.snapshots.profile(&profile.id).unwrap())
            .unwrap();
        assert_eq!(review.files as usize, expected.len());
        let done = start(f, &review, "backup");
        let key = done.snapshot_id.unwrap();
        keys.push(key.clone());
        let restore = f
            .library
            .snapshots
            .restore_review(
                &f.library,
                f.library.snapshots.profile(&profile.id).unwrap(),
                &key,
                Fixture::selection(&f.output),
            )
            .unwrap();
        let output = f
            .output
            .join(format!("stillharbour-restored-{}", restore.id));
        start(f, &restore, "restore");
        for (relative, bytes) in &expected {
            assert_eq!(
                std::fs::read(output.join("roots").join(&f.root).join(relative)).unwrap(),
                *bytes
            );
            let file = File::open(f.source.join(relative)).unwrap();
            assert_eq!(filesystem::identity(&file).unwrap(), before[relative].0);
            assert_eq!(
                file.metadata().unwrap().modified().unwrap(),
                before[relative].1
            );
            assert_eq!(std::fs::read(f.source.join(relative)).unwrap(), *bytes);
        }
        verify_catalog(
            &output.join("Catalog.snapshot.stillharbour"),
            &run.catalog,
            crate::catalog::SCHEMA_VERSION,
        )
        .unwrap();
    }
    assert_ne!(keys[0], keys[1]);
    let p = f.library.snapshots.profile(&profile.id).unwrap();
    let history = f.library.snapshots.records(&p).unwrap();
    assert_eq!(history.len(), 2);
    assert!(
        keys.iter()
            .all(|key| history.iter().any(|record| &record.id == key))
    );
    // Restore OLD again after the damaged version was included and verified.
    let review = f
        .library
        .snapshots
        .restore_review(&f.library, p, &keys[0], Fixture::selection(&f.output))
        .unwrap();
    let old = f
        .output
        .join(format!("stillharbour-restored-{}", review.id));
    start(f, &review, "restore");
    assert_eq!(
        std::fs::read(old.join("roots").join(&f.root).join("photo.jpg")).unwrap(),
        good
    );
    assert_eq!(std::fs::read(f.source.join("photo.jpg")).unwrap(), damaged);
    assert_eq!(
        std::fs::read(neighbor).unwrap(),
        b"retain this separately generated neighbor"
    );
}
